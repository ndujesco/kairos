def partner_questions():
    """Return searchable records plus real bullet-list data for HTML/Markdown."""
    records = []
    for service, question, intro, candidates in SECTIONS:
        partners = []
        for key, role, *override in candidates:
            name, url = PROVIDERS[key]
            partners.append(dict(key=key, name=name, url=override[0] if override else url, role=role))
        # Existing search reads question + answer + category. Keep all supplier
        # names and roles in answer, while rendering the structured list below.
        answer = intro + "\n\n" + "\n".join(f'{p["name"]}: {p["role"]}.' for p in partners)
        records.append(dict(id=f"cp-{service}", category=CATEGORY,
                            question=question, answer=answer, priority=True,
                            partner_intro=intro, partners=partners,
                            checked=CHECKED))
    return records
